//   size    cells along the item's longer side. 1 cell ≈ 10 cm, and sizes are
//           kept honest relative to each other — and to Stretchy, whose nap
//           takes a 3×2 space: much bigger than his bowls, a bit smaller
//           than his bag of kibble.
//   weight  1 light · 2 medium · 3 HEAVY (heavy items can't touch fragile ones)
//   fragile glass, ceramic, frames
//   t       silhouette threshold override (see tools/derive.mjs)
//   shape   hand-drawn override, rows of "#" and "." — used when a silhouette
//           doesn't read well as a grid piece
